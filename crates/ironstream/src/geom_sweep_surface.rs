// FILE: geom_sweep_surface.rs
//! `Geom_SweptSurface` — base and concrete swept-surface types, mirroring
//! OpenCascade's `Geom_SweptSurface` hierarchy from TKG3d.
//!
//! ## Hierarchy
//!
//! ```text
//! Geom_Surface
//!   └─ Geom_SweptSurface            (abstract in OCCT — here: GeomSweptSurface enum)
//!         ├─ Geom_SurfaceOfLinearExtrusion  → re-exported from geom_extrusion_surface
//!         └─ Geom_SurfaceOfRevolution       → re-exported from geom_revol_surface
//! ```
//!
//! ### Geom_SweptSurface
//! The abstract base stores the **basis curve** and the **direction** (for
//! extrusion) or **axis** (for revolution).  In Rust we model this as an
//! owning enum `GeomSweptSurface` whose variants carry the two concrete types.
//!
//! ### Geom_SurfaceOfLinearExtrusion
//! `P(U, V) = C(U) + V * Direction` — already implemented fully in
//! `geom_extrusion_surface`.  Re-exported here for the combined API.
//!
//! ### Geom_SurfaceOfRevolution
//! `P(U, V) = Rot(U, axis) · C(V)` — already implemented fully in
//! `geom_revol_surface`.  Re-exported here for the combined API.
//!
//! This module adds:
//! - `GeomSweptSurface` — the unified dispatch enum.
//! - `SweptSurfaceKind` — a lightweight tag enum.
//! - Convenience constructors and a uniform surface evaluation API.

