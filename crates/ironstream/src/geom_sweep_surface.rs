// ─────────────────────────── SweptSurfaceKind ───────────────────────────────

/// Tag identifying the kind of a swept surface.
///
/// Mirrors `STANDARD_TYPE` queries in OCCT that distinguish the two concrete
/// subclasses of `Geom_SweptSurface`.
// occt: Geom_SweptSurface (kind tag)
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SweptSurfaceKind {
    /// `Geom_SurfaceOfLinearExtrusion` — linear sweep (prism).
    LinearExtrusion,
    /// `Geom_SurfaceOfRevolution` — rotational sweep.
    Revolution,
}

// ─────────────────────────── GeomSweptSurface ───────────────────────────────

/// `Geom_SweptSurface` — a surface generated by sweeping a basis curve.
///
/// This Rust enum models the abstract base class from OCCT's TKG3d. Both
/// concrete variants share:
///
/// - A **basis curve** (the profile being swept).
/// - A **sweep direction** — either a linear direction vector (`Extrusion`)
///   or a rotational axis (`Revolution`).
///
/// The enum dispatches `value`, `d0`, `d1`, `dn`, `u_iso`, `v_iso` and
/// topology queries uniformly to the appropriate concrete implementation.
// occt: Geom_SweptSurface
#[derive(Clone, Debug)]
pub enum GeomSweptSurface {
    /// `Geom_SurfaceOfLinearExtrusion` variant.
    Extrusion(GeomSurfaceOfLinearExtrusion),
    /// `Geom_SurfaceOfRevolution` variant.
    Revolution(GeomSurfaceOfRevolution),
}

impl GeomSweptSurface {
    // ────────────────────────── constructors ─────────────────────────────────

    /// Build a linear-extrusion swept surface.
    ///
    /// Mirrors `Geom_SurfaceOfLinearExtrusion(C, V)`.
    pub fn new_extrusion(basis: GeomCurve, direction: Vec3) -> Self {
        GeomSweptSurface::Extrusion(GeomSurfaceOfLinearExtrusion::new(basis, direction))
    }

    /// Build a revolution swept surface.
    ///
    /// Mirrors `Geom_SurfaceOfRevolution(C, Ax1)`.
    pub fn new_revolution(basis: BasisCurve, axis: Ax1) -> Self {
        GeomSweptSurface::Revolution(GeomSurfaceOfRevolution::new(basis, axis))
    }

    // ─────────────────────────── kind ────────────────────────────────────────

    /// Return the [`SweptSurfaceKind`] tag for this surface.
    pub fn kind(&self) -> SweptSurfaceKind {
        match self {
            GeomSweptSurface::Extrusion(_) => SweptSurfaceKind::LinearExtrusion,
            GeomSweptSurface::Revolution(_) => SweptSurfaceKind::Revolution,
        }
    }

    /// Whether this is an extrusion surface.
    pub fn is_extrusion(&self) -> bool {
        matches!(self, GeomSweptSurface::Extrusion(_))
    }

    /// Whether this is a revolution surface.
    pub fn is_revolution(&self) -> bool {
        matches!(self, GeomSweptSurface::Revolution(_))
    }

    // ─────────────────────── parameter queries ────────────────────────────────

    /// First U parameter of the surface.
    pub fn u_first_parameter(&self) -> f64 {
        match self {
            GeomSweptSurface::Extrusion(s) => s.u_first_parameter(),
            GeomSweptSurface::Revolution(s) => s.u_first_parameter(),
        }
    }

    /// Last U parameter of the surface.
    pub fn u_last_parameter(&self) -> f64 {
        match self {
            GeomSweptSurface::Extrusion(s) => s.u_last_parameter(),
            GeomSweptSurface::Revolution(s) => s.u_last_parameter(),
        }
    }

    /// First V parameter of the surface.
    pub fn v_first_parameter(&self) -> f64 {
        match self {
            GeomSweptSurface::Extrusion(s) => s.v_first_parameter(),
            GeomSweptSurface::Revolution(s) => s.v_first_parameter(),
        }
    }

    /// Last V parameter of the surface.
    pub fn v_last_parameter(&self) -> f64 {
        match self {
            GeomSweptSurface::Extrusion(s) => s.v_last_parameter(),
            GeomSweptSurface::Revolution(s) => s.v_last_parameter(),
        }
    }

    // ─────────────────── topology flags (OCCT virtual interface) ─────────────

    /// `IsUClosed` — whether the surface is closed in U.
    pub fn is_u_closed(&self) -> bool {
        match self {
            GeomSweptSurface::Extrusion(s) => s.is_u_closed(),
            GeomSweptSurface::Revolution(s) => s.is_u_closed(),
        }
    }

    /// `IsVClosed` — whether the surface is closed in V.
    pub fn is_v_closed(&self) -> bool {
        match self {
            GeomSweptSurface::Extrusion(s) => s.is_v_closed(),
            GeomSweptSurface::Revolution(s) => s.is_v_closed(),
        }
    }

    /// `IsUPeriodic` — whether the U parameter is periodic.
    pub fn is_u_periodic(&self) -> bool {
        match self {
            GeomSweptSurface::Extrusion(s) => s.is_u_periodic(),
            GeomSweptSurface::Revolution(s) => s.is_u_periodic(),
        }
    }

    /// `IsVPeriodic` — whether the V parameter is periodic.
    pub fn is_v_periodic(&self) -> bool {
        match self {
            GeomSweptSurface::Extrusion(s) => s.is_v_periodic(),
            GeomSweptSurface::Revolution(s) => s.is_v_periodic(),
        }
    }

    // ───────────────────────── evaluation ────────────────────────────────────

    /// `D0(U, V)` / `Value(U, V)` — the point on the surface.
    pub fn value(&self, u: f64, v: f64) -> Pnt {
        match self {
            GeomSweptSurface::Extrusion(s) => s.value(u, v),
            GeomSweptSurface::Revolution(s) => s.value(u, v),
        }
    }

    /// `D0(U, V)` — alias for [`value`](Self::value).
    pub fn d0(&self, u: f64, v: f64) -> Pnt {
        self.value(u, v)
    }

    /// `D1(U, V)` — point and first-order partial derivatives `(P, DU, DV)`.
    pub fn d1(&self, u: f64, v: f64) -> (Pnt, Vec3, Vec3) {
        match self {
            GeomSweptSurface::Extrusion(s) => s.d1(u, v),
            GeomSweptSurface::Revolution(s) => s.d1(u, v),
        }
    }

    /// `DN(U, V, Nu, Nv)` — partial derivative of order `(Nu, Nv)`.
    ///
    /// # Panics
    /// Panics if `nu < 0`, `nv < 0`, or `nu + nv < 1`.
    pub fn dn(&self, u: f64, v: f64, nu: i32, nv: i32) -> Vec3 {
        match self {
            GeomSweptSurface::Extrusion(s) => s.dn(u, v, nu, nv),
            GeomSweptSurface::Revolution(s) => s.dn(u, v, nu, nv),
        }
    }

    // ───────────────────────── iso curves ────────────────────────────────────

    /// `UIso` — iso-curve at constant U as a line.
    ///
    /// For extrusion: a ruling line through `C(U)` along the extrusion direction.
    /// For revolution: not a simple line in general; returns the line approximation
    /// of the rotated basis curve tangent at `U` (the VIso of the revolution at `u`).
    pub fn u_iso_line(&self, u: f64) -> GeomLine {
        match self {
            GeomSweptSurface::Extrusion(s) => s.u_iso(u),
            GeomSweptSurface::Revolution(s) => s.v_iso(u),
        }
    }

    /// `UIso` as a circle — only valid for revolution surfaces (the U-iso of a
    /// revolution is a circle).
    ///
    /// Returns `Some(circle)` for a revolution surface, `None` for extrusion.
    pub fn u_iso_circle(&self, v: f64) -> Option<GeomCircle> {
        match self {
            GeomSweptSurface::Extrusion(_) => None,
            GeomSweptSurface::Revolution(s) => Some(s.u_iso(v)),
        }
    }

    // ─────────────────────────── transforms ──────────────────────────────────

    /// `Transform(T)` — apply an affine transform in-place.
    pub fn transform(&mut self, t: &Trsf) {
        match self {
            GeomSweptSurface::Extrusion(s) => s.transform(t),
            GeomSweptSurface::Revolution(s) => s.transform(t),
        }
    }

    /// Return a transformed copy.
    pub fn transformed(&self, t: &Trsf) -> GeomSweptSurface {
        let mut copy = self.clone();
        copy.transform(t);
        copy
    }

    /// `Copy()` — a deep clone.
    pub fn copy(&self) -> GeomSweptSurface {
        self.clone()
    }

    // ─────────────────────────── normal ──────────────────────────────────────

    /// Unit outward surface normal at `(u, v)` — computed as `DU × DV` normalized.
    ///
    /// Returns `(point, normal)`.
    pub fn normal(&self, u: f64, v: f64) -> (Pnt, Vec3) {
        let (p, du, dv) = self.d1(u, v);
        let n = du.cross(dv);
        let norm = n.norm();
        let unit = if norm > crate::gp::EPS {
            n * (1.0 / norm)
        } else {
            // Degenerate: return fallback Z direction.
            Pnt::new(0.0, 0.0, 1.0)
        };
        (p, unit)
    }

    // ────────────────────── down-cast helpers ─────────────────────────────────

    /// Borrow the inner extrusion surface, if this is an extrusion variant.
    pub fn as_extrusion(&self) -> Option<&GeomSurfaceOfLinearExtrusion> {
        match self {
            GeomSweptSurface::Extrusion(s) => Some(s),
            _ => None,
        }
    }

    /// Borrow the inner revolution surface, if this is a revolution variant.
    pub fn as_revolution(&self) -> Option<&GeomSurfaceOfRevolution> {
        match self {
            GeomSweptSurface::Revolution(s) => Some(s),
            _ => None,
        }
    }
}

// ─────────────── convenience constructors (stand-alone functions) ────────────

/// Build a cylinder surface (`Geom_SurfaceOfRevolution`) of radius `r` around
/// the Z axis.
///
/// This is the canonical OCCT pattern: revolve a line at distance `r` from
/// the Z axis, parallel to Z, by 2π.
pub fn make_cylinder_revolution(r: f64) -> GeomSurfaceOfRevolution {
    let basis = BasisCurve::line(Pnt::new(r, 0.0, 0.0), Pnt::new(0.0, 0.0, 1.0));
    let axis = Ax1::new(Pnt::origin(), Pnt::new(0.0, 0.0, 1.0));
    GeomSurfaceOfRevolution::new(basis, axis)
}

/// Build a circular-extrusion surface of radius `r`, swept along direction `d`.
///
/// The circle is in the XY plane (identity frame). The extrusion direction is
/// `d` (normalized on construction).
pub fn make_circle_extrusion(r: f64, direction: Vec3) -> GeomSurfaceOfLinearExtrusion {
    let circle = GeomCircle::from_ax3(Ax3::identity(), r);
    GeomSurfaceOfLinearExtrusion::new(GeomCurve::Circle(circle), direction)
}

/// Build a torus-like revolution surface by revolving a circle of radius `minor_r`
/// whose center is at distance `major_r` from the Z axis.
///
/// The circle's center is at `(major_r, 0, 0)`, the circle plane is the XZ plane.
/// Revolving around the Z axis gives a torus.
pub fn make_torus_revolution(major_r: f64, minor_r: f64) -> GeomSurfaceOfRevolution {
    // Circle center offset from Z axis, lying in the XZ plane.
    let center = Pnt::new(major_r, 0.0, 0.0);
    // The circle is in the XZ plane: X direction = +X, Y direction = +Z.
    let pos = Ax3 {
        location: center,
        x_dir: Pnt::new(1.0, 0.0, 0.0),
        y_dir: Pnt::new(0.0, 0.0, 1.0),
        z_dir: Pnt::new(0.0, -1.0, 0.0),
    };
    let basis = BasisCurve::circle(pos, minor_r);
    let axis = Ax1::new(Pnt::origin(), Pnt::new(0.0, 0.0, 1.0));
    GeomSurfaceOfRevolution::new(basis, axis)
}

