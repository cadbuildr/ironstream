//! # IronStream
//!
//! A from-scratch CAD geometry kernel written in pure Rust with **zero
//! third-party dependencies**. IronStream is an original, clean-room
//! implementation: it shares no code with OpenCascade/OCCT or any other CAD
//! kernel. Only published algorithms (e.g. BSP CSG, ear clipping) are common
//! knowledge.
//!
//! ## Boundary
//!
//! The public API deliberately mirrors OpenCascade's **package boundary** so a
//! reader familiar with OCCT finds the same shape:
//!
//! | OCCT package        | IronStream module      | Contents                                   |
//! |---------------------|------------------------|--------------------------------------------|
//! | `gp`                | [`gp`]                 | points, vectors, axes, transforms          |
//! | `Geom`              | [`geom`]               | analytic surface/curve descriptors         |
//! | `TopoDS`            | [`topods`]             | `Vertex`/`Wire`/`Face`/`Solid`/`Compound`  |
//! | `BRepBuilderAPI`    | [`brep_builder_api`]   | polygon/face builders, transforms          |
//! | `BRepPrimAPI`       | [`brep_prim_api`]      | box/cyl/sphere/cone/torus, prism, revol    |
//! | `BRepAlgoAPI`       | [`brep_algo_api`]      | fuse / cut / common (boolean)              |
//! | `BRepMesh`          | [`mesh`]               | the triangle mesh + volume/bbox/area       |
//! | `StlAPI` / `STEP`   | [`mesh_io`]            | binary STL and faceted STEP writers        |
//!
//! Internally IronStream is a **tessellating** kernel: solids are watertight
//! triangle meshes, and booleans run through a BSP-tree CSG engine ([`bsp`]).
//! Analytic surface kinds are retained as metadata ([`geom`]) for a future
//! exact-geometry path.
//!
//! ## Example
//!
//! ```
//! use ironstream::prelude::*;
//! let a = make_box(Pnt::origin(), 10.0, 10.0, 10.0);
//! let b = make_cylinder(3.0, 10.0, MeshParams::default());
//! let drilled = cut(&a, &b);
//! assert!(drilled.volume() < a.volume());
//! ```

