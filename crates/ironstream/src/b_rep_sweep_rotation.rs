#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_rotation_creation() {
        let origin = (0.0, 0.0, 0.0);
        let direction = (0.0, 0.0, 1.0);
        let axis = GpAx1::new(origin, direction);
        let shape = TopoDS_Shape::new();
        let num_shape = SweepNumShape;
        let location = TopLocLocation;

        let rotation = BRepSweepRotation::new(&shape, &num_shape, &location, &axis, 1.57, false);
        assert!((rotation.angle() - 1.57).abs() < 1e-10);
        assert_eq!(rotation.copy, false);
    }

    #[test]
    fn test_rotation_axis() {
        let origin = (1.0, 2.0, 3.0);
        let direction = (1.0, 0.0, 0.0);
        let axis = GpAx1::new(origin, direction);
        let shape = TopoDS_Shape::new();
        let num_shape = SweepNumShape;
        let location = TopLocLocation;

        let rotation = BRepSweepRotation::new(&shape, &num_shape, &location, &axis, 3.14, true);
        let retrieved_axis = rotation.axe();
        let (ox, oy, oz) = retrieved_axis.origin();
        assert!((ox - 1.0).abs() < 1e-10);
        assert!((oy - 2.0).abs() < 1e-10);
        assert!((oz - 3.0).abs() < 1e-10);
        assert_eq!(rotation.copy, true);
    }

    #[test]
    fn test_rotation_query_methods() {
        let origin = (0.0, 0.0, 0.0);
        let direction = (0.0, 0.0, 1.0);
        let axis = GpAx1::new(origin, direction);
        let shape = TopoDS_Shape::new();
        let num_shape = SweepNumShape;
        let location = TopLocLocation;

        let rotation = BRepSweepRotation::new(&shape, &num_shape, &location, &axis, 2.0, false);

        let _ = rotation.make_empty_vertex(&shape, &num_shape);
        let _ = rotation.make_empty_directing_edge(&shape, &num_shape);
        let _ = rotation.make_empty_generating_edge(&shape, &num_shape);
        let _ = rotation.make_empty_face(&shape, &num_shape);
        let _ = rotation.has_shape(&shape, &num_shape);
        let _ = rotation.is_invariant(&shape);
    }
}
