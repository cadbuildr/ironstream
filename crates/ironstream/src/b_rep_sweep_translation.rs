#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_translation_creation() {
        let vec = GpVec::new(1.0, 2.0, 3.0);
        let shape = TopoDS_Shape::new();
        let num_shape = SweepNumShape;
        let location = TopLocLocation;

        let translation = BRepSweepTranslation::new(&shape, &num_shape, &location, &vec, false, true);
        assert_eq!(translation.canonize, true);
    }

    #[test]
    fn test_translation_vec() {
        let vec = GpVec::new(5.0, 6.0, 7.0);
        let shape = TopoDS_Shape::new();
        let num_shape = SweepNumShape;
        let location = TopLocLocation;

        let translation = BRepSweepTranslation::new(&shape, &num_shape, &location, &vec, true, false);
        let retrieved_vec = translation.vec();

        assert!((retrieved_vec.x() - 5.0).abs() < 1e-10);
        assert!((retrieved_vec.y() - 6.0).abs() < 1e-10);
        assert!((retrieved_vec.z() - 7.0).abs() < 1e-10);
    }

    #[test]
    fn test_translation_query_methods() {
        let vec = GpVec::new(1.0, 0.0, 0.0);
        let shape = TopoDS_Shape::new();
        let num_shape = SweepNumShape;
        let location = TopLocLocation;

        let translation = BRepSweepTranslation::new(&shape, &num_shape, &location, &vec, false, true);

        let _ = translation.make_empty_vertex(&shape, &num_shape);
        let _ = translation.make_empty_directing_edge(&shape, &num_shape);
        let _ = translation.make_empty_generating_edge(&shape, &num_shape);
        let _ = translation.make_empty_face(&shape, &num_shape);
        let _ = translation.has_shape(&shape, &num_shape);
        let _ = translation.is_invariant(&shape);
    }

    #[test]
    fn test_translation_zero_vec() {
        let vec = GpVec::new(0.0, 0.0, 0.0);
        let shape = TopoDS_Shape::new();
        let num_shape = SweepNumShape;
        let location = TopLocLocation;

        let translation = BRepSweepTranslation::new(&shape, &num_shape, &location, &vec, false, false);
        let retrieved_vec = translation.vec();

        assert!((retrieved_vec.x() - 0.0).abs() < 1e-10);
        assert!((retrieved_vec.y() - 0.0).abs() < 1e-10);
        assert!((retrieved_vec.z() - 0.0).abs() < 1e-10);
    }
}
