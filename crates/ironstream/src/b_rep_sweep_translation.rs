/// Provides an algorithm to build object by translation sweep.
pub struct BRepSweepTranslation {
    vec: (f64, f64, f64),
    canonize: bool,
}

impl BRepSweepTranslation {
    /// Creates a topology by translating S with the vector V.
    /// If C is true S components are copied.
    /// If Canonize is true then generated surfaces are attempted to be canonized in simple types.
    pub fn new(
        _s: &TopoDS_Shape,
        _n: &SweepNumShape,
        _l: &TopLocLocation,
        v: &GpVec,
        _c: bool,
        canonize: bool,
    ) -> Self {
        BRepSweepTranslation {
            vec: (v.x(), v.y(), v.z()),
            canonize,
        }
    }

    /// Builds the vertex addressed by [aGenV,aDirV].
    pub fn make_empty_vertex(
        &self,
        _a_gen_v: &TopoDS_Shape,
        _a_dir_v: &SweepNumShape,
    ) -> TopoDS_Shape {
        TopoDS_Shape::new()
    }

    /// Builds the edge addressed by [aGenV,aDirE].
    pub fn make_empty_directing_edge(
        &self,
        _a_gen_v: &TopoDS_Shape,
        _a_dir_e: &SweepNumShape,
    ) -> TopoDS_Shape {
        TopoDS_Shape::new()
    }

    /// Builds the edge addressed by [aGenE,aDirV].
    pub fn make_empty_generating_edge(
        &self,
        _a_gen_e: &TopoDS_Shape,
        _a_dir_v: &SweepNumShape,
    ) -> TopoDS_Shape {
        TopoDS_Shape::new()
    }

    /// Sets the parameters of the new vertex on the new face.
    pub fn set_parameters(
        &self,
        _a_new_face: &TopoDS_Shape,
        _a_new_vertex: &mut TopoDS_Shape,
        _a_gen_f: &TopoDS_Shape,
        _a_gen_v: &TopoDS_Shape,
        _a_dir_v: &SweepNumShape,
    ) {
    }

    /// Sets the parameter of the new vertex on the new edge (directing).
    pub fn set_directing_parameter(
        &self,
        _a_new_edge: &TopoDS_Shape,
        _a_new_vertex: &mut TopoDS_Shape,
        _a_gen_v: &TopoDS_Shape,
        _a_dir_e: &SweepNumShape,
        _a_dir_v: &SweepNumShape,
    ) {
    }

    /// Sets the parameter of the new vertex on the new edge (generating).
    pub fn set_generating_parameter(
        &self,
        _a_new_edge: &TopoDS_Shape,
        _a_new_vertex: &mut TopoDS_Shape,
        _a_gen_e: &TopoDS_Shape,
        _a_gen_v: &TopoDS_Shape,
        _a_dir_v: &SweepNumShape,
    ) {
    }

    /// Builds the face addressed by [aGenS,aDirS].
    pub fn make_empty_face(
        &self,
        _a_gen_s: &TopoDS_Shape,
        _a_dir_s: &SweepNumShape,
    ) -> TopoDS_Shape {
        TopoDS_Shape::new()
    }

    /// Sets the PCurve for a new edge on a new face.
    pub fn set_pcurve(
        &self,
        _a_new_face: &TopoDS_Shape,
        _a_new_edge: &mut TopoDS_Shape,
        _a_gen_f: &TopoDS_Shape,
        _a_gen_e: &TopoDS_Shape,
        _a_dir_v: &SweepNumShape,
        _orien: i32,
    ) {
    }

    /// Sets the PCurve for a new edge on a new face (generating).
    pub fn set_generating_pcurve(
        &self,
        _a_new_face: &TopoDS_Shape,
        _a_new_edge: &mut TopoDS_Shape,
        _a_gen_e: &TopoDS_Shape,
        _a_dir_e: &SweepNumShape,
        _a_dir_v: &SweepNumShape,
        _orien: i32,
    ) {
    }

    /// Sets the PCurve for a new edge on a new face (directing).
    pub fn set_directing_pcurve(
        &self,
        _a_new_face: &TopoDS_Shape,
        _a_new_edge: &mut TopoDS_Shape,
        _a_gen_e: &TopoDS_Shape,
        _a_gen_v: &TopoDS_Shape,
        _a_dir_e: &SweepNumShape,
        _orien: i32,
    ) {
    }

    /// Returns the Orientation of the shell in the solid generated by the face aGenS.
    pub fn direct_solid(&self, _a_gen_s: &TopoDS_Shape, _a_dir_s: &SweepNumShape) -> i32 {
        0
    }

    /// Returns true if aNewSubShape must be added in aNewShape.
    pub fn ggd_shape_is_to_add(
        &self,
        _a_new_shape: &TopoDS_Shape,
        _a_new_sub_shape: &TopoDS_Shape,
        _a_gen_s: &TopoDS_Shape,
        _a_sub_gen_s: &TopoDS_Shape,
        _a_dir_s: &SweepNumShape,
    ) -> bool {
        false
    }

    /// Returns true if aNewSubShape (addressed by aGenS and aSubDirS) must be added.
    pub fn gdd_shape_is_to_add(
        &self,
        _a_new_shape: &TopoDS_Shape,
        _a_new_sub_shape: &TopoDS_Shape,
        _a_gen_s: &TopoDS_Shape,
        _a_dir_s: &SweepNumShape,
        _a_sub_dir_s: &SweepNumShape,
    ) -> bool {
        false
    }

    /// Returns true if the topology of a generated face must be composed of independent closed wires.
    pub fn separated_wires(
        &self,
        _a_new_shape: &TopoDS_Shape,
        _a_new_sub_shape: &TopoDS_Shape,
        _a_gen_s: &TopoDS_Shape,
        _a_sub_gen_s: &TopoDS_Shape,
        _a_dir_s: &SweepNumShape,
    ) -> bool {
        false
    }

    /// Returns true if aDirS and aGenS addresses a resulting Shape.
    pub fn has_shape(&self, _a_gen_s: &TopoDS_Shape, _a_dir_s: &SweepNumShape) -> bool {
        false
    }

    /// Returns true if the geometry of aGenS is not modified by the translation.
    pub fn is_invariant(&self, _a_gen_s: &TopoDS_Shape) -> bool {
        false
    }

    /// Returns the Vector of the Prism.
    pub fn vec(&self) -> GpVec {
        GpVec::new(self.vec.0, self.vec.1, self.vec.2)
    }
}

